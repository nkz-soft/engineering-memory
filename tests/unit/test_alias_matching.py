"""Wherever a project is named in a conversation, it is found — SC-001, AM-1, AM-4, AR-2.

Six places can carry text a person or a tool wrote, and a project is as likely to be named in a
pasted path inside a tool result as in a title ChatGPT generated from the first question. The
title is in fact the weakest signal of the six: it is often autogenerated and about the question
rather than the project.
"""

from __future__ import annotations

from datetime import UTC, datetime

from hermes_memory.classification import UNKNOWN_PROJECT
from hermes_memory.classification.alias_classifier import AliasProjectClassifier
from hermes_memory.normalization import (
    Conversation,
    Message,
    NonTextKind,
    NonTextPart,
    ProjectTag,
    Role,
    Source,
    ToolActivity,
)
from tests.synthetic import projects

STARTED_AT = datetime(2026, 3, 4, 9, 30, tzinfo=UTC)

CLASSIFIER = AliasProjectClassifier(projects.rule_set())
EXPECTED = ProjectTag(value="orchard-pipeline")


def conversation(
    *,
    title: str | None = None,
    text: str = "",
    tool_activity: tuple[ToolActivity, ...] = (),
    non_text_parts: tuple[NonTextPart, ...] = (),
) -> Conversation:
    return Conversation(
        source=Source.CHATGPT,
        source_id="placement1",
        title=title,
        started_at=STARTED_AT,
        messages=(
            Message(
                role=Role.ASSISTANT,
                text=text,
                sent_at=STARTED_AT,
                tool_activity=tool_activity,
                non_text_parts=non_text_parts,
            ),
        ),
    )


def test_the_alias_in_the_title_is_found() -> None:
    assert CLASSIFIER.classify(conversation(title=f"{projects.ALIAS} retries")) == EXPECTED


def test_the_alias_in_a_message_is_found() -> None:
    assert CLASSIFIER.classify(conversation(text=f"we moved {projects.ALIAS}")) == EXPECTED


def test_the_alias_in_a_tool_name_is_found() -> None:
    found = CLASSIFIER.classify(
        conversation(tool_activity=(ToolActivity(name=f"{projects.ALIAS}-deploy"),))
    )

    assert found == EXPECTED


def test_the_alias_in_a_tool_request_is_found() -> None:
    found = CLASSIFIER.classify(
        conversation(tool_activity=(ToolActivity(name="search", request=projects.ALIAS),))
    )

    assert found == EXPECTED


def test_the_alias_in_a_tool_result_is_found() -> None:
    found = CLASSIFIER.classify(
        conversation(
            tool_activity=(
                ToolActivity(name="search", request="where", result=f"D:/src/{projects.ALIAS}"),
            )
        )
    )

    assert found == EXPECTED


def test_the_alias_in_an_attachment_name_is_found() -> None:
    found = CLASSIFIER.classify(
        conversation(
            non_text_parts=(NonTextPart(kind=NonTextKind.FILE, name=f"{projects.ALIAS}.log"),)
        )
    )

    assert found == EXPECTED


def test_the_alias_in_the_source_id_is_not_found() -> None:
    """AM-8. A native identifier that happens to contain an alias is a coincidence."""
    found = AliasProjectClassifier(projects.rule_set()).classify(
        Conversation(
            source=Source.CHATGPT,
            source_id=f"{projects.ALIAS}-9fa1",
            title=None,
            started_at=STARTED_AT,
        )
    )

    assert found == UNKNOWN_PROJECT


def test_a_different_case_still_matches() -> None:
    """AM-1."""
    assert CLASSIFIER.classify(conversation(text=projects.ALIAS.upper())) == EXPECTED


def test_a_multi_word_alias_split_across_a_line_break_still_matches() -> None:
    """AM-4. A person names a project in prose, and prose wraps."""
    classifier = AliasProjectClassifier(
        projects.rule_set(projects.rule("orchard-pipeline", "orchard pipeline"))
    )

    assert classifier.classify(conversation(text="the orchard\npipeline run")) == EXPECTED


def test_one_match_wins_whatever_its_priority() -> None:
    """AR-2. Priority only ever decides between projects; it never disqualifies a lone match."""
    classifier = AliasProjectClassifier(
        projects.rule_set(projects.rule("orchard-pipeline", projects.ALIAS, priority=-5))
    )

    assert classifier.classify(conversation(text=projects.ALIAS)) == EXPECTED


def test_several_aliases_of_one_project_are_one_answer() -> None:
    """AR-5. Not ambiguity: one project, one answer."""
    classifier = AliasProjectClassifier(
        projects.rule_set(projects.rule("orchard-pipeline", projects.ALIAS, "orchard"))
    )

    assert classifier.classify(conversation(text=f"{projects.ALIAS} and orchard")) == EXPECTED
